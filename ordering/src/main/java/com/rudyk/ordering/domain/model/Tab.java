package com.rudyk.ordering.domain.model;

import javax.persistence.*;
import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.*;

@Entity
@Table(name = "tabs")
public class Tab {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "tab_id")
    private Long id;

    @Column(nullable = false)
    private int tableNumber;

    @Column(nullable = false)
    private LocalDateTime openedAt;

    private LocalDateTime closedAt;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private TabStatus status;

    @OneToMany(mappedBy = "tab", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<OrderItem> orderItems = new ArrayList<>();

    @Column(nullable = false, precision = 15, scale = 2)
    private BigDecimal total = BigDecimal.ZERO;

    protected Tab() {
        // JPA
    }

    private Tab(int tableNumber) {
        this.tableNumber = tableNumber;
        this.openedAt = LocalDateTime.now();
        this.status = TabStatus.OPEN;
        this.total = BigDecimal.ZERO;
    }

    /** Factory: open a new tab (id will be generated by DB). */
    public static Tab open(int tableNumber) {
        return new Tab(tableNumber);
    }

    public void confirm() {
        if (status != TabStatus.OPEN) {
            throw new IllegalStateException("Tab need to be opened before confirming it");
        }
        if (orderItems.isEmpty()) {
            throw new IllegalStateException("Cannot confirm an empty tab.");
        }
        this.status = TabStatus.CONFIRMED;
    }

    /** Add an item and update total. Ensure the back-reference is set. */
    public void addItem(OrderItem item) {
        if (status != TabStatus.OPEN) {
            throw new IllegalStateException("Cannot add items to a closed tab");
        }
        item.setTab(this); // make sure OrderItem has setTab(Tab)
        this.orderItems.add(item);
        this.total = this.total.add(item.getPrice()); // or item.getTotalPrice() if you model quantity in price
    }

    /** Remove by item code and update total. */
    public boolean removeItem(String itemCode) {
        for (Iterator<OrderItem> it = orderItems.iterator(); it.hasNext(); ) {
            OrderItem item = it.next();
            if (item.getItemCode().equals(itemCode)) {
                total = total.subtract(item.getPrice());
                it.remove();
                return true;
            }
        }
        return false;
    }

    /** Update quantity by code and refresh total accordingly. */
    public boolean updateItemQuantity(String itemCode, int newQuantity) {
        for (OrderItem item : orderItems) {
            if (item.getItemCode().equals(itemCode)) {
                total = total.subtract(item.getPrice());
                item.setQuantity(newQuantity); // ensure OrderItem has a setter and recalculates its price if needed
                total = total.add(item.getPrice());
                return true;
            }
        }
        return false;
    }

    /** Close the tab. */
    public void close() {
        if (status == TabStatus.CLOSED ) {
            throw new IllegalStateException("Tab already closed");
        }

        if (orderItems.isEmpty()) {
            throw new IllegalStateException("Cannot close an empty tab");
        }
        this.closedAt = LocalDateTime.now();
        this.status = TabStatus.CLOSED;
    }

    // -------- Getters --------

    public Long getId() {
        return id;
    }

    public int getTableNumber() {
        return tableNumber;
    }

    public LocalDateTime getOpenedAt() {
        return openedAt;
    }

    public LocalDateTime getClosedAt() {
        return closedAt;
    }

    public TabStatus getStatus() {
        return status;
    }

    public List<OrderItem> getOrderItems() {
        return Collections.unmodifiableList(orderItems);
    }

    public BigDecimal getTotal() {
        return total;
    }

    @Override
    public String toString() {
        return "Tab{" +
                "id=" + id +
                ", tableNumber=" + tableNumber +
                ", openedAt=" + openedAt +
                ", closedAt=" + closedAt +
                ", status=" + status +
                ", total=" + total +
                ", items=" + orderItems.size() +
                '}';
    }
}